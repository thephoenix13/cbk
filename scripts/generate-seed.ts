// Generates supabase/seed.sql from the bundled defaults.
// Run: npx vite-node scripts/generate-seed.ts
import { writeFileSync } from "node:fs";
import { DEFAULT_CLIENTS, DEFAULT_PROJECTS, SECTIONS, SETTINGS_DEFAULTS } from "../src/content/sections";

const json = (value: unknown) => `$j$${JSON.stringify(value)}$j$::jsonb`;

const sectionRows = SECTIONS.map((s, i) => ({ page: s.page, key: s.key, data: s.defaults, sort_order: i }));
const clientRows = DEFAULT_CLIENTS.map((c, i) => ({
  name: c.name, logo_url: `/clients/${c.file}`, sort_order: i, is_published: true,
}));

const sql = `-- Generated by scripts/generate-seed.ts. Safe to re-run: existing rows are left alone.

insert into public.site_settings (id, data)
values (1, ${json(SETTINGS_DEFAULTS)})
on conflict (id) do nothing;

insert into public.page_sections (page, key, data, sort_order)
select x.page, x.key, x.data, x.sort_order
from jsonb_to_recordset(${json(sectionRows)}) as x(page text, key text, data jsonb, sort_order int)
on conflict (page, key) do nothing;

insert into public.clients (name, logo_url, sort_order, is_published)
select x.name, x.logo_url, x.sort_order, x.is_published
from jsonb_to_recordset(${json(clientRows)}) as x(name text, logo_url text, sort_order int, is_published boolean)
where not exists (select 1 from public.clients);

insert into public.projects (title, client, location, category, summary, highlights, cover_url, gallery, sort_order, is_published)
select x.title, x.client, x.location, x.category, x.summary,
       array(select jsonb_array_elements_text(x.highlights)),
       x.cover_url,
       array(select jsonb_array_elements_text(x.gallery)),
       x.sort_order, x.is_published
from jsonb_to_recordset(${json(DEFAULT_PROJECTS)}) as x(
  title text, client text, location text, category text, summary text,
  highlights jsonb, cover_url text, gallery jsonb, sort_order int, is_published boolean
)
where not exists (select 1 from public.projects);
`;

writeFileSync("supabase/seed.sql", sql);
console.log(`seed.sql written (${sql.length} bytes)`);
